#!/usr/bin/env node
// SPEC-CAP: generate the capability risk table from the normative registry.
// Regenerate with: npm run generate:capability-risk
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { collectDeviceCapabilities } from "./generate-device-registry.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..");
const REGISTRY_PATH = join(
  ROOT,
  "specs",
  "spec-cap",
  "registry",
  "capability-risk.json",
);
const SCHEMA_PATH = join(
  ROOT,
  "specs",
  "spec-cap",
  "schema",
  "capability-risk.schema.json",
);
const DEVICE_REGISTRY_PATH = join(
  ROOT,
  "specs",
  "spec-device",
  "registry",
  "device-classes.json",
);
const PROTOCOL_OUT = join(
  ROOT,
  "packages",
  "protocol",
  "src",
  "capability-risk.gen.ts",
);

const RISK_RANK = { benign: 0, elevated: 1, sensitive: 2, critical: 3 };

export function minimumRiskRank(entry) {
  let rank = RISK_RANK.benign;
  if (entry.readsSensorSecretOrForeignData) {
    rank = Math.max(rank, RISK_RANK.elevated);
  }
  if (entry.namesDestination || entry.irreversibleOrThirdParty) {
    rank = Math.max(rank, RISK_RANK.sensitive);
  }
  return rank;
}

export function assertRiskAssignment(entry) {
  const assigned = RISK_RANK[entry.riskClass];
  if (assigned === undefined) {
    throw new Error(`${entry.id}: unknown risk class ${entry.riskClass}`);
  }
  const floor = minimumRiskRank(entry);
  if (assigned < floor) {
    throw new Error(
      `${entry.id}: risk class ${entry.riskClass} is below the floor implied by its answers`,
    );
  }
  if (entry.riskClass === "critical" && !entry.irreversibleOrThirdParty) {
    throw new Error(
      `${entry.id}: critical requires irreversibleOrThirdParty (harms people who never approved)`,
    );
  }
}

function defaultDeviceRiskClass(consentClass, id) {
  if (id === "device:share-policy:read") return "benign";
  if (consentClass === "low") return "elevated";
  return "sensitive";
}

export function generateCapabilityRisk(registryPath = REGISTRY_PATH) {
  const registry = JSON.parse(readFileSync(registryPath, "utf8"));
  const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
  if (schema.title !== "CapabilityRiskRegistry") {
    throw new Error("unexpected capability-risk schema title");
  }
  const listed = registry.capabilities;
  if (!Array.isArray(listed) || listed.length === 0) {
    throw new Error("capability-risk registry has no capabilities");
  }

  const byId = new Map();
  for (const entry of listed) {
    if (byId.has(entry.id)) {
      throw new Error(`duplicate capability risk id ${entry.id}`);
    }
    assertRiskAssignment(entry);
    byId.set(entry.id, entry);
  }

  const deviceRegistry = JSON.parse(readFileSync(DEVICE_REGISTRY_PATH, "utf8"));
  for (const device of collectDeviceCapabilities(deviceRegistry)) {
    const entry = byId.get(device.id);
    if (entry === undefined) {
      throw new Error(
        `capability-risk.json missing device capability ${device.id}`,
      );
    }
    const expected = defaultDeviceRiskClass(device.consentClass, device.id);
    if (entry.riskClass !== expected) {
      throw new Error(
        `${device.id}: expected ${expected} from consent class ${device.consentClass}, got ${entry.riskClass}`,
      );
    }
  }

  const rows = registry.capabilities.map((entry) => ({
    id: entry.id,
    riskClass: entry.riskClass,
    namesDestination: entry.namesDestination,
    irreversibleOrThirdParty: entry.irreversibleOrThirdParty,
    readsSensorSecretOrForeignData: entry.readsSensorSecretOrForeignData,
    standing: entry.standing,
  }));

  const protocolSource = `// Generated by scripts/generate-capability-risk.mjs — do not edit.
// Source: specs/spec-cap/registry/capability-risk.json

export type CapabilityRiskClass = "benign" | "elevated" | "sensitive" | "critical";

export interface CapabilityRiskEntry {
  readonly id: string;
  readonly riskClass: CapabilityRiskClass;
  readonly namesDestination: boolean;
  readonly irreversibleOrThirdParty: boolean;
  readonly readsSensorSecretOrForeignData: boolean;
  readonly standing: boolean;
}

export const CAPABILITY_RISK_HOST_API = ${JSON.stringify(registry.hostApiVersion)} as const;

export const CAPABILITY_RISK_REGISTRY: ReadonlyArray<CapabilityRiskEntry> = ${JSON.stringify(rows, null, 2)} as const;

const CAPABILITY_RISK_BY_ID = new Map(
  CAPABILITY_RISK_REGISTRY.map((entry) => [entry.id, entry]),
);

export function capabilityRiskById(id: string): CapabilityRiskEntry | undefined {
  return CAPABILITY_RISK_BY_ID.get(id);
}

export function riskClassForCapability(id: string): CapabilityRiskClass {
  const entry = capabilityRiskById(id);
  if (entry === undefined) {
    throw new Error(\`unknown capability risk id: \${id}\`);
  }
  return entry.riskClass;
}
`;

  writeFileSync(PROTOCOL_OUT, protocolSource);
  return {
    capabilityCount: rows.length,
    deviceCount: collectDeviceCapabilities(deviceRegistry).length,
  };
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) ===
    (await import("node:path")).resolve(process.argv[1]);
if (invokedDirectly) {
  const result = generateCapabilityRisk();
  console.log(
    `generated capability risk: ${result.capabilityCount} capabilities (${result.deviceCount} device) →`,
  );
  console.log(`  ${PROTOCOL_OUT}`);
}
