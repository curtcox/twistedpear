#!/usr/bin/env node
/**
 * Bundle the Guida compiler and embed elm/core + elm/json + vendored
 * TwistedPear sources for offline on-device compile.
 * Regenerated with: npm run generate:guida-compiler-asset
 */
import { spawnSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const PKG = join(ROOT, "packages/guida-twistedpear");
const SRC = join(PKG, "src");

function walkFiles(root, prefix = "") {
  /** @type {Array<{ path: string, content: string }>} */
  const files = [];
  for (const name of readdirSync(root).sort()) {
    const full = join(root, name);
    const rel = prefix === "" ? name : `${prefix}/${name}`;
    if (statSync(full).isDirectory()) {
      files.push(...walkFiles(full, rel));
    } else {
      files.push({ path: rel, content: readFileSync(full, "utf8") });
    }
  }
  return files;
}

function asRecord(files) {
  /** @type {Record<string, string>} */
  const record = {};
  for (const file of files) {
    record[file.path] = file.content;
  }
  return record;
}

function writeSeedModule() {
  const vendor = asRecord(walkFiles(join(PKG, "elm")));
  const home = {};
  for (const file of walkFiles(join(PKG, "seed"))) {
    home[`1.0.0/packages/${file.path}`] = file.content;
  }
  const body = `/** Generated by scripts/generate-guida-compiler-asset.mjs. Do not edit. */
export const VENDOR_FILES = ${JSON.stringify(vendor)};
export const GUIDA_HOME_FILES = ${JSON.stringify(home)};
`;
  writeFileSync(join(SRC, "seed-files.generated.js"), body);
}

function bundleGuida() {
  const entry = join(ROOT, "node_modules/guida/lib/index.js");
  const outfile = join(SRC, "guida-lib.generated.js");
  const bundled = spawnSync(
    process.execPath,
    [
      join(ROOT, "node_modules/esbuild/bin/esbuild"),
      entry,
      "--bundle",
      "--format=esm",
      "--platform=browser",
      `--outfile=${outfile}`,
      "--log-level=warning",
    ],
    { cwd: ROOT, encoding: "utf8" },
  );
  if (bundled.status !== 0) {
    throw new Error(
      `esbuild guida failed: ${(bundled.stderr || bundled.stdout || "").slice(0, 800)}`,
    );
  }
}

writeSeedModule();
bundleGuida();
console.log("wrote packages/guida-twistedpear/src/seed-files.generated.js");
console.log("wrote packages/guida-twistedpear/src/guida-lib.generated.js");
