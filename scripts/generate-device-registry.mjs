#!/usr/bin/env node
// SPEC-DEVICE: generate TypeScript tables from the normative device-class registry.
// Regenerate with: npm run generate:device-registry
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const ROOT = join(here, "..");
const REGISTRY_PATH = join(
  ROOT,
  "specs",
  "spec-device",
  "registry",
  "device-classes.json",
);
const SCHEMA_PATH = join(
  ROOT,
  "specs",
  "spec-device",
  "schema",
  "device-registry.schema.json",
);
const PROTOCOL_OUT = join(
  ROOT,
  "packages",
  "protocol",
  "src",
  "device-registry.gen.ts",
);
const CAPS_OUT = join(
  ROOT,
  "packages",
  "miniapp-runtime",
  "src",
  "device-capabilities.gen.ts",
);

function capabilityId(classId, suffix) {
  return suffix === null || suffix === undefined
    ? `device:${classId}`
    : `device:${classId}:${suffix}`;
}

function capabilityDescription(entry, tier) {
  const tierLabel =
    tier.capabilitySuffix === null ? "default tier" : `${tier.id} tier`;
  return `${entry.description} (${tierLabel}; consent: ${tier.consentClass}).`;
}

/** Device capability rows derived from the class registry (tiers + cross-cutting). */
export function collectDeviceCapabilities(registry) {
  const capabilities = [];
  for (const entry of registry.classes) {
    for (const tier of entry.tiers) {
      capabilities.push({
        id: capabilityId(entry.id, tier.capabilitySuffix),
        description: capabilityDescription(entry, tier),
        classId: entry.id,
        tierId: tier.id,
        consentClass: tier.consentClass,
        isDefaultTier: tier.default,
      });
    }
  }
  for (const cross of registry.crossCutting) {
    capabilities.push({
      id: cross.id,
      description: cross.description,
      classId: null,
      tierId: null,
      consentClass: cross.consentClass,
      isDefaultTier: false,
    });
  }
  return capabilities;
}

export function generateDeviceRegistry(registryPath = REGISTRY_PATH) {
  const registry = JSON.parse(readFileSync(registryPath, "utf8"));
  const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
  if (schema.title !== "DeviceClassRegistry") {
    throw new Error("unexpected device registry schema title");
  }

  const defaultTierCounts = new Map();
  for (const entry of registry.classes) {
    const defaults = entry.tiers.filter((tier) => tier.default);
    if (defaults.length !== 1) {
      throw new Error(
        `device class ${entry.id} must have exactly one default tier`,
      );
    }
    defaultTierCounts.set(entry.id, defaults[0].id);
    for (const tierId of Object.keys(entry.bandwidth)) {
      if (!entry.tiers.some((tier) => tier.id === tierId)) {
        throw new Error(
          `bandwidth profile ${tierId} has no matching tier on ${entry.id}`,
        );
      }
    }
  }

  const capabilities = collectDeviceCapabilities(registry);

  const ids = new Set();
  for (const capability of capabilities) {
    if (ids.has(capability.id))
      throw new Error(`duplicate capability id ${capability.id}`);
    ids.add(capability.id);
  }

  const protocolSource = `// Generated by scripts/generate-device-registry.mjs — do not edit.
// Source: specs/spec-device/registry/device-classes.json

export type DeviceConsentClass = "low" | "elevated" | "sensitive";
export type DeviceRole = "sensor" | "actuator" | "transducer" | "service";

export interface DeviceBandwidthProfile {
  readonly minBps: number;
  readonly targetBps: number;
  readonly burstBytes: number;
  readonly encodings?: Readonly<Record<string, DeviceEncodingBandwidthProfile>>;
}

export interface DeviceEncodingBandwidthProfile {
  readonly minBps: number;
  readonly targetBps: number;
  readonly burstBytes: number;
}

export interface DeviceTierDefinition {
  readonly id: string;
  readonly default: boolean;
  readonly consentClass: DeviceConsentClass;
  readonly capabilitySuffix: string | null;
}

export interface DeviceClassDefaults {
  readonly maxRateHz: number;
  readonly maxSessionMs: number;
  readonly dutyCycle?: number;
}

export interface DeviceClassEntry {
  readonly id: string;
  readonly role: DeviceRole;
  readonly addedInHostApi: string;
  readonly tiers: ReadonlyArray<DeviceTierDefinition>;
  readonly sampleSchema: string;
  readonly defaults: DeviceClassDefaults;
  readonly streamable: boolean;
  readonly remoteEligible: boolean;
  readonly bandwidth: Readonly<Record<string, DeviceBandwidthProfile>>;
  readonly consentClass: DeviceConsentClass;
  readonly degradationLadder: ReadonlyArray<string>;
  readonly description: string;
}

export const DEVICE_REGISTRY_HOST_API = ${JSON.stringify(registry.hostApiVersion)} as const;

export const DEVICE_CLASS_REGISTRY: ReadonlyArray<DeviceClassEntry> = ${JSON.stringify(registry.classes, null, 2)} as const;

export function deviceClassById(id: string): DeviceClassEntry | undefined {
  return DEVICE_CLASS_REGISTRY.find((entry) => entry.id === id);
}

export function defaultTierForClass(entry: DeviceClassEntry): DeviceTierDefinition {
  const tier = entry.tiers.find((candidate) => candidate.default);
  if (tier === undefined) {
    throw new Error(\`device class \${entry.id} has no default tier\`);
  }
  return tier;
}

export function deviceCapabilityId(classId: string, tierId?: string): string {
  const entry = deviceClassById(classId);
  if (entry === undefined) {
    throw new Error(\`unknown device class: \${classId}\`);
  }
  const tier = tierId === undefined
    ? defaultTierForClass(entry)
    : entry.tiers.find((candidate) => candidate.id === tierId);
  if (tier === undefined) {
    throw new Error(\`unknown tier \${tierId} for device class \${classId}\`);
  }
  return tier.capabilitySuffix === null
    ? \`device:\${classId}\`
    : \`device:\${classId}:\${tier.capabilitySuffix}\`;
}
`;

  const capsSource = `// Generated by scripts/generate-device-registry.mjs — do not edit.
// Source: specs/spec-device/registry/device-classes.json

export interface DeviceCapabilityDefinition {
  readonly id: ${capabilities.map((c) => JSON.stringify(c.id)).join(" | ")};
  readonly description: string;
  readonly classId: string | null;
  readonly tierId: string | null;
  readonly consentClass: "low" | "elevated" | "sensitive";
  readonly isDefaultTier: boolean;
}

export const DEVICE_CAPABILITY_DEFINITIONS = ${JSON.stringify(capabilities, null, 2)} as const satisfies ReadonlyArray<DeviceCapabilityDefinition>;

export type DeviceCapability = typeof DEVICE_CAPABILITY_DEFINITIONS[number]["id"];
`;

  writeFileSync(PROTOCOL_OUT, protocolSource);
  writeFileSync(CAPS_OUT, capsSource);
  return {
    classCount: registry.classes.length,
    capabilityCount: capabilities.length,
    defaultTierCounts: Object.fromEntries(defaultTierCounts),
  };
}

const invokedDirectly =
  process.argv[1] !== undefined &&
  fileURLToPath(import.meta.url) ===
    (await import("node:path")).resolve(process.argv[1]);
if (invokedDirectly) {
  const result = generateDeviceRegistry();
  console.log(
    `generated device registry: ${result.classCount} classes, ${result.capabilityCount} capabilities →`,
  );
  console.log(`  ${PROTOCOL_OUT}`);
  console.log(`  ${CAPS_OUT}`);
}
